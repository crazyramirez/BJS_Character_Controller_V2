#!/usr/bin/env node
// Builds the runtime as an npm-ready package in dist/lib/:
//   character-controller.js   classic <script> build (UMD BABYLON global) — a copy of js/character-controller.js
//   character-controller.mjs  ES module generated from the same source
//   character-controller.d.ts hand-written types (types/character-controller.d.ts)
//   package.json, README.md
// Usage: node scripts/build-lib.mjs [--out <dir>]
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = path.join(ROOT, 'js', 'character-controller.js');
const TYPES = path.join(ROOT, 'types', 'character-controller.d.ts');
const PACKAGE_NAME = 'bjs-character-controller';

// Everything the ES module exports (all are top-level declarations of the source).
export const ESM_EXPORTS = [
  'S', 'ACTION_STATES', 'KEYS', 'DEFAULT_CHAR_CONFIG', 'BAKED_PRESET', 'CHARACTER_PRESET_SCHEMA',
  'STANDARD_ANIM_SLOTS', 'AnimCtrl', 'CharCtrl', 'LocoBlendGroup',
  'setupCharacter', 'createCharacter', 'initPhysics',
  'applyCharacterPreset', 'normalizeCharacterPreset', 'resolveCharacterPreset',
  'normBone', 'cleanAnimName', 'lerp', 'lerpAngle',
  'BJSRetarget', 'canonicalBoneRole', 'readGlbJson', 'buildRetargetBoneMap', 'loadRetargetSource',
  'retargetAnimationGroupsClient', 'measureLocomotionClip',
];

/** Turn the classic-script source into an ES module body. */
export function toEsmSource(source, { version = '0.0.0' } = {}) {
  let body = source.replace(/^﻿?'use strict';\s*/, ''); // modules are strict already
  if (/^export\s/m.test(body)) throw new Error('character-controller.js must stay a classic script (no exports).');
  for (const name of ESM_EXPORTS) {
    const declared = new RegExp(`^(?:const|let|class|function|async function) ${name}\\b`, 'm');
    if (!declared.test(body)) throw new Error(`build-lib: "${name}" is not a top-level declaration of the source.`);
  }
  return `// ${PACKAGE_NAME} ${version} — ES module build of js/character-controller.js.
// Generated by scripts/build-lib.mjs. Do not edit: change the source and rebuild.
//
//   import * as BABYLON from '@babylonjs/core';
//   import '@babylonjs/loaders/glTF';
//   import { useBabylon, createCharacter } from '${PACKAGE_NAME}';
//   useBabylon(BABYLON);
//
// Without useBabylon() the global BABYLON (UMD script) is used.

/* eslint-disable */
let BABYLON = globalThis.BABYLON;

/**
 * Provide the Babylon.js namespace (\`import * as BABYLON from '@babylonjs/core'\`).
 * options.havok: HavokPhysics factory or instance used by initPhysics/createCharacter
 * when they are not given one explicitly.
 */
export function useBabylon(namespace, options = {}) {
  if (!namespace || typeof namespace !== 'object') throw new TypeError('useBabylon(namespace) expects the Babylon.js namespace object.');
  BABYLON = namespace;
  if (options && options.havok) initPhysics.havok = options.havok;
  return namespace;
}

/** The Babylon.js namespace currently in use. */
export function getBabylon() { return BABYLON; }

${body.trimEnd()}

export {
  ${ESM_EXPORTS.join(',\n  ')},
  setupCharacter as loadCharacter,
  retargetAnimationGroupsClient as retargetAnimationGroups,
};
`;
}

