/** Build into `outDir` (default dist/lib). Returns the written file paths. */
export async function buildLib({ outDir = path.join(ROOT, 'dist', 'lib') } = {}) {
  const [source, rootPackageText, types] = await Promise.all([
    fs.readFile(SOURCE, 'utf8'),
    fs.readFile(path.join(ROOT, 'package.json'), 'utf8'),
    fs.readFile(TYPES, 'utf8'),
  ]);
  const rootPackage = JSON.parse(rootPackageText);
  const files = {
    'character-controller.js': source,
    'character-controller.mjs': toEsmSource(source, { version: rootPackage.version }),
    'character-controller.d.ts': types,
    'package.json': JSON.stringify(libPackageJson(rootPackage), null, 2) + '\n',
    'README.md': libReadme(rootPackage.version),
  };
  await fs.mkdir(outDir, { recursive: true });
  const written = [];
  for (const [name, content] of Object.entries(files)) {
    const target = path.join(outDir, name);
    await fs.writeFile(target, content);
    written.push(target);
  }
  return written;
}

const invokedDirectly = process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;
if (invokedDirectly) {
  const outIndex = process.argv.indexOf('--out');
  const outDir = outIndex > 0 && process.argv[outIndex + 1] ? path.resolve(process.argv[outIndex + 1]) : undefined;
  const written = await buildLib({ outDir });
  console.log(`[build:lib] Wrote ${written.length} files to ${path.dirname(written[0])}`);
}
